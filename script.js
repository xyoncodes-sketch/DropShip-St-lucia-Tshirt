let cart = JSON.parse(localStorage.getItem('shoppingCart')) || [];

// Initialize
document.addEventListener('DOMContentLoaded', () => {
    updateCartCount();
    
    // If we are on the checkout page, render the items
    if (document.getElementById('checkout-cart-items')) {
        renderCheckoutCart();
        renderPayPalButton();
    }

    // If we are on the product details page, load the product
    if (document.getElementById('product-details-page')) {
        loadProductDetails();
    }

    // If we are on the receipt page
    if (document.getElementById('receipt-details')) {
        loadReceipt();
    }

    // Handle Checkout Form (EmailJS)
    const checkoutForm = document.getElementById('checkout-form');
    if (checkoutForm) {
        checkoutForm.addEventListener('submit', handleCheckoutForm);
    }
});

function updateCartCount() {
    const countElement = document.getElementById('cart-count');
    if (countElement) {
        countElement.innerText = cart.length;
    }
}

// Add item to cart
function addToCart(productId, size) {
    const product = products.find(p => p.id === productId);
    if (product) {
        // Clone the product and add the selected size (default to 'M' if not specified)
        const cartItem = { ...product, size: size || 'M' };
        cart.push(cartItem);
        localStorage.setItem('shoppingCart', JSON.stringify(cart));
        updateCartCount();
    }
}

function toggleCart() {
    window.location.href = 'checkout.html';
}

function toggleMenu() {
    const navLinks = document.querySelector('.nav-links');
    const menuToggle = document.querySelector('.menu-toggle');
    navLinks.classList.toggle('active');
    menuToggle.classList.toggle('active');
}

function renderCheckoutCart() {
    const container = document.getElementById('checkout-cart-items');
    const totalEl = document.getElementById('checkout-total');
    const hiddenInput = document.getElementById('order-details-input');
    
    container.innerHTML = '';
    let total = 0;

    if (cart.length === 0) {
        container.innerHTML = '<p style="text-align: center; color: #666; padding: 1rem;">Your cart is empty. <a href="index.html#products" style="color: #0087D1;">Start Shopping</a></p>';
    }

    cart.forEach((item, index) => {
        total += item.price;
        const div = document.createElement('div');
        div.className = 'checkout-item';
        div.innerHTML = `
            <img src="${item.image}" alt="${item.name}" class="checkout-img">
            <div class="item-info">
                <strong>${item.name}</strong>
                <span>Size: ${item.size || 'M'}</span>
                <span>$${item.price.toFixed(2)}</span>
            </div>
            <button onclick="removeFromCart(${index})" class="remove-btn">Remove</button>
        `;
        container.appendChild(div);
    });

    totalEl.innerText = total.toFixed(2);
    
    // Fill hidden input for email
    if (hiddenInput) {
        const itemsList = cart.map(i => `${i.name} (${i.size || 'M'}) - $${i.price}`).join(', ');
        hiddenInput.value = `TOTAL: $${total.toFixed(2)} \nITEMS: ${itemsList}`;
    }

    // Render Payment Link if available (e.g. Stripe)
    const linkContainer = document.getElementById('payment-link-container');
    if (linkContainer) {
        linkContainer.innerHTML = '';
        // Only show direct link if cart has 1 item and that item has a specific link
        if (cart.length === 1 && cart[0].stripeLink) {
            const btn = document.createElement('a');
            btn.href = cart[0].stripeLink;
            btn.target = '_blank';
            btn.className = 'cta-button';
            btn.innerText = 'Pay with Card (Direct Link)';
            btn.style.cssText = 'display: block; text-align: center; background-color: #635bff; color: white; width: 100%; text-decoration: none; margin-top: 1rem; border: none;';
            linkContainer.appendChild(btn);
        }
    }
}

function removeFromCart(index) {
    cart.splice(index, 1);
    localStorage.setItem('shoppingCart', JSON.stringify(cart));
    renderCheckoutCart();
    updateCartCount();
}

function loadProductDetails() {
    const params = new URLSearchParams(window.location.search);
    const id = parseInt(params.get('id'));
    const product = products.find(p => p.id === id);
    
    if (product) {
        document.getElementById('product-image').src = product.image;
        document.getElementById('product-name').innerText = product.name;
        document.getElementById('product-price').innerText = '$' + product.price.toFixed(2);
        
        const addBtn = document.getElementById('add-to-cart-btn');
        addBtn.onclick = function() {
            const size = document.getElementById('size-select').value;
            addToCart(product.id, size);
        };

        // Render Stripe Buy Now Button if link exists
        const buyNowContainer = document.getElementById('paypal-buy-now-button-container');
        if (buyNowContainer) {
            buyNowContainer.innerHTML = '';
            const orDivider = buyNowContainer.previousElementSibling;
            
            if (product.stripeLink) {
                const btn = document.createElement('a');
                btn.href = product.stripeLink;
                btn.className = 'cta-button';
                btn.innerText = 'Buy Now';
                btn.style.cssText = 'display: block; text-align: center; background-color: #635bff; color: white; width: 100%; text-decoration: none; margin-top: 0;';
                buyNowContainer.appendChild(btn);
                if (orDivider) orDivider.style.display = 'block';
            } else if (orDivider) {
                orDivider.style.display = 'none';
            }
        }
    } else {
        document.querySelector('.product-details-wrapper').innerHTML = '<h2>Product not found</h2><a href="index.html" class="cta-button">Back to Home</a>';
    }
}

function renderPayPalButton() {
    if (typeof paypal !== 'undefined' && document.getElementById('paypal-button-container')) {
        document.getElementById('paypal-button-container').innerHTML = '';
        paypal.Buttons({
            createOrder: function(data, actions) {
                const total = cart.reduce((sum, item) => sum + item.price, 0);
                return actions.order.create({
                    purchase_units: [{
                        amount: {
                            currency_code: 'USD',
                            value: total.toFixed(2)
                        }
                    }]
                });
            },
            onApprove: function(data, actions) {
                return actions.order.capture().then(function(details) {
                    // Save order details for receipt
                    const orderData = {
                        id: details.id,
                        date: new Date().toLocaleString(),
                        method: 'PayPal',
                        total: parseFloat(details.purchase_units[0].amount.value),
                        items: [...cart],
                        customer: {
                            name: details.payer.name.given_name + ' ' + details.payer.name.surname,
                            email: details.payer.email_address
                        }
                    };
                    localStorage.setItem('lastOrder', JSON.stringify(orderData));

                    // Clear cart
                    cart = [];
                    localStorage.setItem('shoppingCart', JSON.stringify(cart));
                    updateCartCount();
                    
                    // Redirect to receipt
                    window.location.href = 'receipt.html';
                });
            },
            onError: function(err) {
                console.error('PayPal Error:', err);
                alert('An error occurred with the payment. Please try again.');
            }
        }).render('#paypal-button-container');
    }
}

// Handle EmailJS submission
async function handleCheckoutForm(e) {
    e.preventDefault();
    const form = e.target;
    const formData = new FormData(form);
    const submitBtn = form.querySelector('button[type="submit"]');
    
    submitBtn.disabled = true;
    submitBtn.innerText = 'Processing...';

    // Calculate total
    const total = cart.reduce((sum, item) => sum + item.price, 0);

    const orderData = {
        id: 'ORD-' + Math.floor(Math.random() * 1000000),
        date: new Date().toLocaleString(),
        method: 'Standard Checkout',
        total: total,
        items: [...cart],
        customer: {
            name: formData.get('name'),
            email: formData.get('email'),
            address: formData.get('address')
        }
    };

    try {
        // Replace with your Service ID and Template ID from EmailJS
        const serviceID = 'YOUR_SERVICE_ID';
        const templateID = 'YOUR_TEMPLATE_ID';

        const response = await emailjs.sendForm(serviceID, templateID, form);
        
        if (response.status === 200) {
            localStorage.setItem('lastOrder', JSON.stringify(orderData));
            cart = [];
            localStorage.setItem('shoppingCart', JSON.stringify(cart));
            window.location.href = 'receipt.html';
        } else {
            alert('There was a problem submitting your order. Please try again.');
            submitBtn.disabled = false;
            submitBtn.innerText = 'Place Order';
        }
    } catch (error) {
        console.error('EmailJS Error:', error);
        alert('There was a network error. Please try again.');
        submitBtn.disabled = false;
        submitBtn.innerText = 'Place Order';
    }
}

function loadReceipt() {
    const container = document.getElementById('receipt-details');
    const orderData = JSON.parse(localStorage.getItem('lastOrder'));
    
    if (!orderData) {
        container.innerHTML = '<p style="text-align:center">No recent order found.</p>';
        return;
    }
    
    const itemsHtml = orderData.items.map(item => `
        <div class="receipt-row">
            <span>${item.name} (${item.size || 'M'})</span>
            <span>$${item.price.toFixed(2)}</span>
        </div>
    `).join('');

    container.innerHTML = `
        <div class="receipt-header">
            <div class="receipt-success-icon">✓</div>
            <h2>Thank You for Your Order!</h2>
            <p>Order ID: <strong>${orderData.id}</strong></p>
            <p>Date: ${orderData.date}</p>
        </div>
        <div style="margin-bottom: 2rem;">
            <h3>Order Summary</h3>
            ${itemsHtml}
            <div class="cart-total">Total Paid: $${orderData.total.toFixed(2)}</div>
        </div>
        <div>
            <h3>Customer Details</h3>
            <p><strong>Name:</strong> ${orderData.customer.name}</p>
            <p><strong>Email:</strong> ${orderData.customer.email}</p>
            ${orderData.customer.address ? `<p><strong>Shipping to:</strong><br>${orderData.customer.address}</p>` : ''}
        </div>
    `;
}