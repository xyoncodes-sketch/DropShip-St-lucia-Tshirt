// Handle EmailJS submission
async function handleCheckoutForm(e) {
    e.preventDefault();
    const form = e.target;
    const formData = new FormData(form);
    const submitBtn = form.querySelector('button[type="submit"]');
    
    submitBtn.disabled = true;
    submitBtn.innerText = 'Processing...';

    // Calculate total
    const total = cart.reduce((sum, item) => sum + item.price, 0);

    const orderData = {
        id: 'ORD-' + Math.floor(Math.random() * 1000000),
        date: new Date().toLocaleString(),
        method: 'Standard Checkout',
        total: total,
        items: [...cart],
        customer: {
            name: formData.get('name'),
            email: formData.get('email'),
            address: formData.get('address')
        }
    };

    try {
        // Replace with your Service ID and Template ID from EmailJS
        const serviceID = 'YOUR_SERVICE_ID';
        const templateID = 'YOUR_TEMPLATE_ID';

        const response = await emailjs.sendForm(serviceID, templateID, form);
        
        if (response.status === 200) {
            localStorage.setItem('lastOrder', JSON.stringify(orderData));
            cart = [];
            localStorage.setItem('shoppingCart', JSON.stringify(cart));
            window.location.href = 'receipt.html';
        } else {
            alert('There was a problem submitting your order. Please try again.');
            submitBtn.disabled = false;
            submitBtn.innerText = 'Place Order';
        }
    } catch (error) {
        console.error('EmailJS Error:', error);
        alert('There was a network error. Please try again.');
        submitBtn.disabled = false;
        submitBtn.innerText = 'Place Order';
    }
}

